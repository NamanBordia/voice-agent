class MockSourceNode(FrameProcessor):
    """Streams test audio chunked with simulated delay, wrapped in VAD frames."""
    def __init__(self, audio_data: bytes):
        super().__init__()
        self._audio_data = audio_data

    async def process_frame(self, frame: Frame, direction: FrameDirection = FrameDirection.DOWNSTREAM):
        await super().process_frame(frame, direction)
        await self.push_frame(frame, direction)
        
        if isinstance(frame, StartFrame):
            # Signal user started speaking
            await self.push_frame(VADUserStartedSpeakingFrame())
            
            # Chunk the audio to simulate real-time streaming, preventing 
            # Deepgram from rejecting a massive single frame or skewing metrics.
            # 48000Hz, 16-bit stereo PCM = 192000 bytes/sec.
            # 8192 bytes chunk is ~42.6ms of audio.
            chunk_size = 8192 
            chunk_duration = 0.0426
            for i in range(0, len(self._audio_data), chunk_size):
                chunk = self._audio_data[i:i+chunk_size]
                await self.push_frame(InputAudioRawFrame(audio=chunk, sample_rate=48000, num_channels=2))
                await asyncio.sleep(chunk_duration)
            
            # Signal user stopped speaking so Deepgram finalizes the transcription
            await self.push_frame(VADUserStoppedSpeakingFrame())
            
            # Give Deepgram a moment to process the remaining buffer before ending
            await asyncio.sleep(3.0)
            await self.pipeline_task.queue_frame(EndFrame())

class MetricsCollector(FrameProcessor):
    """Intercepts transcription frames to measure response latency."""
    def __init__(self):
        super().__init__()
        self.start_time = None
        self.first_transcription_time = None
        self.captured_text = ""

    async def process_frame(self, frame: Frame, direction: FrameDirection = FrameDirection.DOWNSTREAM):
        await super().process_frame(frame, direction)
        
        if self.start_time is None:
            self.start_time = time.time()
            
        if isinstance(frame, TranscriptionFrame):
            if self.first_transcription_time is None:
                self.first_transcription_time = time.time()
            self.captured_text += frame.text + " "
            
        elif isinstance(frame, EndFrame):
            end_time = time.time()
            if self.first_transcription_time:
                latency = self.first_transcription_time - self.start_time
                print(f"\n[STT METRICS] Time to First Transcription: {latency:.3f}s")
                print(f"[STT METRICS] Transcribed Text: '{self.captured_text.strip()}'")
            else:
                print(f"\n[STT METRICS] No transcription received. Total execution: {end_time - self.start_time:.3f}s")

        await self.push_frame(frame, direction)


@pytest.mark.live
@pytest.mark.asyncio
async def test_live_stt_metrics():
    """Test Deepgram STT API using a real speech WAV file."""
    settings = get_settings()
    
    # We construct DeepgramSTTService directly without Flux-specific query params
    # to avoid signature mismatch warnings/type errors in deepgram-sdk.
    stt = DeepgramSTTService(
        api_key=settings.deepgram_api_key,
        sample_rate=48000,
        settings=DeepgramSTTSettings(
            model="nova-2",
            language="en",
            interim_results=False
        ),
    )
    
    # Read the real speech WAV file generated by SAPI5
    wav_path = os.path.abspath("tests/assets/test_speech.wav")
    assert os.path.exists(wav_path), "Test speech WAV file not found"
    
    with open(wav_path, "rb") as f:
        # Skip the 44-byte WAV header to extract pure PCM payload
        f.read(44)
        audio_data = f.read()
    
    source = MockSourceNode(audio_data)
    collector = MetricsCollector()
    
    pipeline = Pipeline([source, stt, collector])
    task = PipelineTask(pipeline, params=PipelineParams(allow_interruptions=False))
    runner = PipelineRunner()
    
    print("\n--- Running Isolated Live STT Test ---")
    await runner.run(task)
    
    # Validation: We expect Deepgram to catch the speech and yield transcription
    assert collector.first_transcription_time is not None
    assert len(collector.captured_text.strip()) > 0
